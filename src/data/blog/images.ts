export function getBlogCover(
  slug: string,
  locale?: Locale,
): { src: string; alt: string } | undefined {
  const base = blogCoverImages[slug];
  if (!base) return undefined;

  const localizedAlt =
    locale && locale !== "en"
      ? blogCoverAltOverrides[locale]?.[slug]
      : undefined;

  return {
    src: base.src,
    alt: localizedAlt ?? base.alt,
  };
}
