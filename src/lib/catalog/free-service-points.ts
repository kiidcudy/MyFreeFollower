export function getHardcodedFreePoints(
  platform: string,
  type: string,
  amount: number,
): number | undefined {
  return FREE_SERVICE_POINTS[key(platform, type, amount)];
}

export function getFreeServicePoints(service: FreeCatalogService): number {
  const hardcoded = getHardcodedFreePoints(service.platform, service.type, service.amount);
  if (hardcoded !== undefined) return hardcoded;
  return Math.max(1, service.amount * 2);
}
