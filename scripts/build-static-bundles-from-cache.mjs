#!/usr/bin/env node
/**
 * Build src/lib/i18n/static-page-bundles.ts from cached locale JSON files in
 * scripts/cache/static-pages/*.json (one file per locale: de.json, fr.json, ...).
 *
 * Usage:
 *   node scripts/build-static-bundles-from-cache.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");

const CACHE_DIR = path.join(__dirname, "cache/static-pages");
const OUT_FILE = path.join(ROOT, "src/lib/i18n/static-page-bundles.ts");

function loadAllCaches() {
  const bundles = {};
  if (!fs.existsSync(CACHE_DIR)) {
    throw new Error(`Cache directory not found: ${CACHE_DIR}`);
  }
  const files = fs
    .readdirSync(CACHE_DIR)
    .filter((f) => f.endsWith(".json") && !f.endsWith(".partial.json"));
  for (const file of files) {
    const locale = file.replace(/\.json$/, "");
    const data = JSON.parse(fs.readFileSync(path.join(CACHE_DIR, file), "utf8"));
    bundles[locale] = data;
  }
  return bundles;
}

function serializeObject(obj, indent = 4) {
  const pad = " ".repeat(indent);
  const lines = Object.entries(obj).map(
    ([k, v]) => `${pad}${k}: ${JSON.stringify(v)},`,
  );
  return `{\n${lines.join("\n")}\n${" ".repeat(indent - 2)}}`;
}

function writeOutputFile(allBundles) {
  const localeBlocks = Object.entries(allBundles).map(([locale, data]) => {
    const key = locale.includes("-") ? `"${locale}"` : locale;
    return `  ${key}: {
    faq: ${serializeObject(data.faq, 6)},
    about: ${serializeObject(data.about, 6)},
    legal: ${serializeObject(data.legal, 6)},
    meta: ${serializeObject(data.meta, 6)},
  }`;
  });

  const content = `// Auto-generated by scripts/build-static-bundles-from-cache.mjs — do not edit manually.
import type { Locale } from "@/lib/i18n/config";

export type StaticPageBundle = {
  faq: Record<string, string>;
  about: Record<string, string>;
  legal: Record<string, string>;
  meta: Record<string, string>;
};

export const staticPageBundles: Partial<Record<Locale, StaticPageBundle>> = {
${localeBlocks.join(",\n")}
};
`;
  fs.writeFileSync(OUT_FILE, content, "utf8");
}

function main() {
  const allBundles = loadAllCaches();
  const locales = Object.keys(allBundles);
  if (locales.length === 0) {
    throw new Error(`No locale JSON files found in ${CACHE_DIR}`);
  }
  writeOutputFile(allBundles);
  console.log(`Built ${OUT_FILE} with locales: ${locales.join(", ")}`);
}

main();
